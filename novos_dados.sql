-- Professores
IF NOT EXISTS (SELECT 1 FROM PROFESSOR WHERE NOME = 'Marcelo')
    INSERT PROFESSOR (NOME) VALUES ('Marcelo');
IF NOT EXISTS (SELECT 1 FROM PROFESSOR WHERE NOME = 'Sergio')
    INSERT PROFESSOR (NOME) VALUES ('Sergio');

-- Matérias
IF NOT EXISTS (SELECT 1 FROM MATERIAS WHERE SIGLA = 'ARQ')
    INSERT MATERIAS (SIGLA, NOME, CARGAHORARIA, CURSO, PROFESSOR)
    VALUES ('ARQ', 'Arquitetura de Computadores', 120, 'ENG',
            (SELECT PROFESSOR FROM PROFESSOR WHERE NOME = 'Marcelo'));
IF NOT EXISTS (SELECT 1 FROM MATERIAS WHERE SIGLA = 'APS')
    INSERT MATERIAS (SIGLA, NOME, CARGAHORARIA, CURSO, PROFESSOR)
    VALUES ('APS', 'Analise e Projeto de Sistemas', 96, 'ENG',
            (SELECT PROFESSOR FROM PROFESSOR WHERE NOME = 'Sergio'));
